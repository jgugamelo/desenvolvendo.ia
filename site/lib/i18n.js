export function trackEvent(event, params = {}) {
  if (typeof window === 'undefined') return;
  window.dataLayer = window.dataLayer || [];
  if (typeof window.gtag === 'function') {
    window.gtag('event', event, params);
  } else {
    window.dataLayer.push({ event, ...params });
  }
}
